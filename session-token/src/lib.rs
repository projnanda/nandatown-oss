//! Session-bound token for ACP coding agents.
//!
//! The control plane mints this at session open, over
//! `{agent_id, user_id, session_id, flow_id, jti}`, and delivers it to the agent
//! (as its model-router credential and in its MCP-server config). Both the MCP
//! gateway and the LLM router then **verify the signature** and read the identity
//! straight off the claims, instead of inferring the user from a propagated
//! `traceparent` — so a coding agent's calls stay bound to a user and a flow even
//! across the `bash -c` → tool subprocess tree that drops HTTP headers, and a long
//! turn is never rejected by a short flow-freshness window.
//!
//! This crate is the crypto half only: [`mint_session_token`] and
//! [`verify_session_token`]. The DB-side checks that complete authentication —
//! the `jti` revocation lookup and the flow-participant membership check — stay
//! in the callers (gateway, router), which already own those tables. Keeping them
//! out means this crate needs no database or config dependency and is pure enough
//! to unit-test in full.
//!
//! The token is an HMAC JWT signed with the platform's `AGENT_JWT_SECRET` — the
//! same key and algorithm the existing agent-identity token uses — so a single
//! secret configures the whole coding-agent auth path.

use std::time::{SystemTime, UNIX_EPOCH};

use jsonwebtoken::{Algorithm, DecodingKey, EncodingKey, Header, Validation, decode, encode};
use serde::{Deserialize, Serialize};
use uuid::Uuid;

/// The `aud` (audience) claim stamped on every session token. It makes a session
/// token unambiguously distinguishable from the existing agent-identity JWT,
/// which is signed with the same secret but carries no such audience — so a
/// verifier that both kinds reach (the LLM router) can tell them apart instead of
/// mistaking one for the other.
pub const SESSION_TOKEN_AUDIENCE: &str = "nasiko-coding-session";

/// The verified identity carried by a session token.
///
/// `iat`/`exp` are seconds since the Unix epoch; `exp` is checked by the JWT
/// library on [`verify_session_token`], so expiry is enforced by the signature
/// check itself rather than by a separate freshness window.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct SessionClaims {
    /// The coding-agent integration id (e.g. `"opencode"`) — which agent.
    pub agent_id: String,
    /// The user the session belongs to — for whom.
    pub user_id: String,
    /// The chat session id (A2A contextId) this token is scoped to.
    pub session_id: String,
    /// The flow (== W3C trace id) the turn runs under.
    pub flow_id: String,
    /// Revocation id — a unique id per minted token, recorded by the issuer so a
    /// token can be revoked before its `exp`.
    pub jti: String,
    /// Audience — always [`SESSION_TOKEN_AUDIENCE`]; the discriminator that marks
    /// this as a coding-agent session token.
    pub aud: String,
    /// Issued-at, seconds since the Unix epoch.
    pub iat: u64,
    /// Expiry, seconds since the Unix epoch.
    pub exp: u64,
}

/// The identity to mint a token for. The issuer supplies the four binding
/// identifiers; `jti`, `iat`, and `exp` are generated by [`mint_session_token`].
#[derive(Debug, Clone)]
pub struct SessionTokenInput {
    pub agent_id: String,
    pub user_id: String,
    pub session_id: String,
    pub flow_id: String,
}

/// A freshly minted token plus the bookkeeping the issuer must keep: the `jti`
/// to record for revocation, and the `exp` it was signed with.
#[derive(Debug, Clone)]
pub struct MintedToken {
    /// The signed JWT to hand to the agent.
    pub token: String,
    /// The token's revocation id — store this so the token can be revoked.
    pub jti: String,
    /// Expiry, seconds since the Unix epoch.
    pub expires_at: u64,
}

/// Anything that can go wrong minting or verifying a session token.
#[derive(Debug, thiserror::Error)]
pub enum SessionTokenError {
    /// The signing/verifying secret is empty — fail closed, never fall open.
    #[error("session token secret is not configured")]
    SecretNotConfigured,
    /// No token was supplied where one was required.
    #[error("missing session token")]
    MissingToken,
    /// The token is a valid JWT but not one of ours (no/!matching audience) —
    /// e.g. the agent-identity token. The caller should fall back to its existing
    /// credential path rather than treat this as a failure.
    #[error("not a session token")]
    NotSessionToken,
    /// The token has our audience but has expired.
    #[error("session token expired")]
    Expired,
    /// The library failed to encode the token (should not happen for valid input).
    #[error("failed to mint session token: {0}")]
    Encode(String),
}

/// Mint a session token valid for `ttl_seconds` from now.
///
/// Returns the signed token along with its `jti` and `exp` so the issuer can
/// record the `jti` for revocation and know when the token lapses. Fails closed
/// if `secret` is empty.
pub fn mint_session_token(
    input: &SessionTokenInput,
    secret: &str,
    ttl_seconds: u64,
    algorithm: Algorithm,
) -> Result<MintedToken, SessionTokenError> {
    if secret.is_empty() {
        return Err(SessionTokenError::SecretNotConfigured);
    }
    let now = now_unix();
    let exp = now.saturating_add(ttl_seconds);
    let jti = Uuid::new_v4().to_string();
    let claims = SessionClaims {
        agent_id: input.agent_id.clone(),
        user_id: input.user_id.clone(),
        session_id: input.session_id.clone(),
        flow_id: input.flow_id.clone(),
        jti: jti.clone(),
        aud: SESSION_TOKEN_AUDIENCE.to_owned(),
        iat: now,
        exp,
    };
    let token = encode(
        &Header::new(algorithm),
        &claims,
        &EncodingKey::from_secret(secret.as_bytes()),
    )
    .map_err(|e| SessionTokenError::Encode(e.to_string()))?;
    Ok(MintedToken {
        token,
        jti,
        expires_at: exp,
    })
}

/// Verify a token value (with or without a `Bearer ` prefix) and return its
/// claims. Checks the signature and expiry; the caller still performs the `jti`
/// revocation and flow-participant checks against its own tables.
///
/// Fails closed if `secret` is empty.
pub fn verify_session_token(
    token: &str,
    secret: &str,
    algorithm: Algorithm,
) -> Result<SessionClaims, SessionTokenError> {
    if secret.is_empty() {
        return Err(SessionTokenError::SecretNotConfigured);
    }
    let raw = strip_bearer(token);
    if raw.is_empty() {
        return Err(SessionTokenError::MissingToken);
    }

    let mut validation = Validation::new(algorithm);
    // Require our audience: a token without it (e.g. the agent-identity JWT, same
    // secret) is reported as `NotSessionToken` so the caller falls back.
    validation.set_audience(&[SESSION_TOKEN_AUDIENCE]);
    validation.set_required_spec_claims(&["exp", "aud"]);
    // These tokens are short-lived and the turn lease handles timing, so enforce
    // `exp` strictly rather than with jsonwebtoken's default 60s leeway.
    validation.leeway = 0;

    let key = DecodingKey::from_secret(secret.as_bytes());
    let data = decode::<SessionClaims>(raw, &key, &validation).map_err(|e| match e.kind() {
        // A token that carries our audience but has lapsed: reject it.
        jsonwebtoken::errors::ErrorKind::ExpiredSignature => SessionTokenError::Expired,
        // Anything else — wrong/absent audience, the agent-identity shape, a bad
        // signature, a non-JWT — is "not one of ours". The caller falls back to
        // its existing credential path, which fails closed on a genuinely bad
        // token; only a *valid* session token ever takes the session path.
        _ => SessionTokenError::NotSessionToken,
    })?;
    Ok(data.claims)
}

/// Map an algorithm name (e.g. `AGENT_JWT_ALGORITHM`) to an [`Algorithm`]. Only
/// HMAC variants are supported (the token is signed with a shared secret);
/// anything unknown falls back to HS256.
pub fn parse_algorithm(name: &str) -> Algorithm {
    match name.trim().to_ascii_uppercase().as_str() {
        "HS384" => Algorithm::HS384,
        "HS512" => Algorithm::HS512,
        _ => Algorithm::HS256,
    }
}

/// Strip a case-insensitive `Bearer ` prefix; tolerate a raw token with no prefix.
fn strip_bearer(header: &str) -> &str {
    let trimmed = header.trim();
    match trimmed.get(..7) {
        Some(prefix) if prefix.eq_ignore_ascii_case("bearer ") => trimmed[7..].trim(),
        _ => trimmed,
    }
}

fn now_unix() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0)
}

#[cfg(test)]
mod tests {
    use super::*;

    const SECRET: &str = "test-secret-do-not-use-in-prod";

    fn input() -> SessionTokenInput {
        SessionTokenInput {
            agent_id: "opencode".into(),
            user_id: "11111111-1111-1111-1111-111111111111".into(),
            session_id: "ses_abc".into(),
            flow_id: "0af7651916cd43dd8448eb211c80319c".into(),
        }
    }

    #[test]
    fn mint_then_verify_roundtrips_the_claims() {
        let minted = mint_session_token(&input(), SECRET, 300, Algorithm::HS256).unwrap();
        let claims = verify_session_token(&minted.token, SECRET, Algorithm::HS256).unwrap();
        assert_eq!(claims.agent_id, "opencode");
        assert_eq!(claims.user_id, "11111111-1111-1111-1111-111111111111");
        assert_eq!(claims.session_id, "ses_abc");
        assert_eq!(claims.flow_id, "0af7651916cd43dd8448eb211c80319c");
        assert_eq!(claims.jti, minted.jti);
        assert_eq!(claims.exp, minted.expires_at);
        assert!(claims.exp > claims.iat);
    }

    #[test]
    fn verify_accepts_a_bearer_prefix() {
        let minted = mint_session_token(&input(), SECRET, 300, Algorithm::HS256).unwrap();
        let header = format!("Bearer {}", minted.token);
        assert!(verify_session_token(&header, SECRET, Algorithm::HS256).is_ok());
    }

    #[test]
    fn each_mint_gets_a_unique_jti() {
        let a = mint_session_token(&input(), SECRET, 300, Algorithm::HS256).unwrap();
        let b = mint_session_token(&input(), SECRET, 300, Algorithm::HS256).unwrap();
        assert_ne!(a.jti, b.jti);
    }

    #[test]
    fn wrong_secret_is_not_recognized() {
        // A bad signature can't be trusted as ours, so it reads as NotSessionToken
        // and the caller falls back (its existing path fails closed on it).
        let minted = mint_session_token(&input(), SECRET, 300, Algorithm::HS256).unwrap();
        let err =
            verify_session_token(&minted.token, "other-secret", Algorithm::HS256).unwrap_err();
        assert!(matches!(err, SessionTokenError::NotSessionToken));
    }

    #[test]
    fn expired_token_is_rejected() {
        // Encode a token whose `exp` is comfortably in the past (mint only makes
        // future-dated tokens), then confirm verification reports it expired.
        let now = now_unix();
        let claims = SessionClaims {
            agent_id: "opencode".into(),
            user_id: "u".into(),
            session_id: "ses_abc".into(),
            flow_id: "f".into(),
            jti: Uuid::new_v4().to_string(),
            aud: SESSION_TOKEN_AUDIENCE.into(),
            iat: now - 1_000,
            exp: now - 500,
        };
        let token = encode(
            &Header::new(Algorithm::HS256),
            &claims,
            &EncodingKey::from_secret(SECRET.as_bytes()),
        )
        .unwrap();
        let err = verify_session_token(&token, SECRET, Algorithm::HS256).unwrap_err();
        assert!(matches!(err, SessionTokenError::Expired));
    }

    #[test]
    fn empty_secret_fails_closed_both_ways() {
        assert!(matches!(
            mint_session_token(&input(), "", 300, Algorithm::HS256),
            Err(SessionTokenError::SecretNotConfigured)
        ));
        assert!(matches!(
            verify_session_token("whatever", "", Algorithm::HS256),
            Err(SessionTokenError::SecretNotConfigured)
        ));
    }

    #[test]
    fn agent_shaped_token_without_audience_is_not_a_session_token() {
        // A JWT signed with the same secret but carrying the agent-identity
        // shape (no `aud`) must be reported as NotSessionToken so the caller
        // falls back to its existing credential path instead of rejecting.
        #[derive(serde::Serialize)]
        struct AgentClaims {
            agent_id: String,
            owner_id: String,
            iat: u64,
            exp: u64,
        }
        let now = now_unix();
        let token = encode(
            &Header::new(Algorithm::HS256),
            &AgentClaims {
                agent_id: "opencode".into(),
                owner_id: "owner".into(),
                iat: now,
                exp: now + 300,
            },
            &EncodingKey::from_secret(SECRET.as_bytes()),
        )
        .unwrap();
        let err = verify_session_token(&token, SECRET, Algorithm::HS256).unwrap_err();
        assert!(matches!(err, SessionTokenError::NotSessionToken));
    }

    #[test]
    fn empty_token_is_missing() {
        assert!(matches!(
            verify_session_token("   ", SECRET, Algorithm::HS256),
            Err(SessionTokenError::MissingToken)
        ));
    }
}
